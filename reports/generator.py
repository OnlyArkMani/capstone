"""
Build a SOC-analyst report from a scored query.

    from fusion import score_query
    from reports import build_report, render_markdown

    score  = score_query(query, records)
    report = build_report(query, score, records)
    print(render_markdown(report))

The headline is first, and that is a design decision rather than a layout one
(design §2.9). An analyst working a queue reads the band and stops there when it
is GREEN; everything below — score, case, evidence, reasoning — is the supporting
detail they open when it is not, or when they want to verify a GREEN. Putting the
composite score first would invite reading a number without its context, which is
the failure mode the case taxonomy exists to prevent.

Every number in the reasoning narrative arrives through `narrative.Fact` carrying
a JSON pointer into this report. Nothing here is generated by a language model,
and `test_reports.py` proves it by resolving every figure in the rendered text
back to a value at a real path.
"""

